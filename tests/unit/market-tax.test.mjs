import { dirname as _dn, resolve as _rs, join as _jn } from 'node:path';
import { tmpdir as _td } from 'node:os';
import { fileURLToPath as _fu } from 'node:url';
const ROOT = _rs(_dn(_fu(import.meta.url)), '../..');
const TMP = (name) => _jn(_td(), 'kng-test-' + name + '-');
import fs from 'node:fs'; import assert from 'node:assert';
const { createMarket, MARKET } = await import(ROOT + '/server/src/market.js');
const { CASTLE } = await import(ROOT + '/src/config/siege.js');
const dir = fs.mkdtempSync(TMP('tax'));
const accs = { S: { mail: [] }, B: { mail: [] } }; const accounts = { get: (id) => accs[id], touch() {} };
const mk = createMarket(dir, accounts); const taxes = []; mk.setTax((fee) => taxes.push(fee));
const seller = { id: 'S', user: 's' }, buyer = { id: 'B', user: 'b' };
const ds = { name: 'Ban', jewels: { bless: 10 }, inv: [], zen: 0 }, db = { name: 'Mua', jewels: {}, inv: [], zen: 1e6 };
mk.list(seller, ds, { jewel: 'bless', n: 5, price: 100000 });
const id = Object.keys(mk.dump().listings)[0];
mk.buy(buyer, db, id);
assert.deepEqual(taxes, [5000], 'phí chợ 5% = 5000 chuyển cho hook');
assert.equal(db.zen, 900000, 'người mua trả đúng giá');
const got = accs.S.mail.find((m) => m.goods.zen > 0).goods.zen; assert.equal(got, 95000, 'người bán vẫn nhận giá − phí (không đổi)');
console.log('thuế gửi quỹ:', Math.floor(5000 * CASTLE.taxShare), '(1.5% giá bán)');
console.log('TAX OK'); process.exit(0);
